CREATE TABLE IF NOT EXISTS accounts (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_login_id TEXT UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('ADMIN', 'WORKER')),
    enabled BOOLEAN NOT NULL,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    deleted_at BIGINT,
    failed_login_count INTEGER NOT NULL DEFAULT 0,
    login_locked_at BIGINT,
    CHECK ((role = 'ADMIN' AND admin_login_id IS NOT NULL AND length(trim(admin_login_id)) > 0)
        OR (role = 'WORKER' AND admin_login_id IS NULL)),
    CHECK (deleted_at IS NULL OR enabled = FALSE)
);
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS failed_login_count INTEGER NOT NULL DEFAULT 0;
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS login_locked_at BIGINT;
CREATE TABLE IF NOT EXISTS worker_profiles (
    worker_id BIGINT PRIMARY KEY REFERENCES accounts(account_id) ON DELETE RESTRICT,
    worker_name TEXT NOT NULL,
    sex TEXT CHECK (sex IS NULL OR sex IN ('M', 'F', 'U')),
    age INTEGER CHECK (age IS NULL OR age BETWEEN 0 AND 150)
);
-- No report is not an implicit RUNNING/NORMAL state.
ALTER TABLE worker_profiles ADD COLUMN IF NOT EXISTS monitoring_status TEXT
    CHECK (monitoring_status IS NULL OR monitoring_status IN ('RUNNING', 'STOPPED'));
ALTER TABLE worker_profiles ADD COLUMN IF NOT EXISTS status_reported_at BIGINT;
ALTER TABLE worker_profiles ADD COLUMN IF NOT EXISTS last_seen_at BIGINT;
ALTER TABLE worker_profiles ADD COLUMN IF NOT EXISTS watch_last_seen_at BIGINT;
-- App-confirmed five-minute assessments; no numeric measurements or implicit normal.
ALTER TABLE worker_profiles ADD COLUMN IF NOT EXISTS heart_rate_status TEXT
    CHECK (heart_rate_status IS NULL OR heart_rate_status IN ('NORMAL', 'DANGER'));
ALTER TABLE worker_profiles ADD COLUMN IF NOT EXISTS heart_rate_measured_at BIGINT;
CREATE TABLE IF NOT EXISTS safety_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    worker_id BIGINT NOT NULL REFERENCES worker_profiles(worker_id) ON DELETE RESTRICT,
    occurred_at BIGINT NOT NULL,
    received_at BIGINT NOT NULL,
    event_type TEXT NOT NULL CHECK (event_type IN ('FALL_DETECTED', 'DANGER_ZONE_APPROACH', 'ABNORMAL_VITAL')),
    alert_sender TEXT NOT NULL,
    processed_at BIGINT,
    processed_by BIGINT REFERENCES accounts(account_id) ON DELETE RESTRICT,
    admin_memo VARCHAR(500),
    CHECK ((processed_at IS NULL AND processed_by IS NULL) OR (processed_at IS NOT NULL AND processed_by IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS mobile_tokens (
    token_hash TEXT PRIMARY KEY NOT NULL CHECK (length(token_hash) = 64),
    account_id BIGINT NOT NULL REFERENCES accounts(account_id) ON DELETE RESTRICT,
    issued_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL CHECK (expires_at > issued_at),
    revoked_at BIGINT
);
CREATE INDEX IF NOT EXISTS idx_events_time ON safety_events(occurred_at, event_id);
CREATE INDEX IF NOT EXISTS idx_events_worker_time ON safety_events(worker_id, occurred_at, event_id);
CREATE INDEX IF NOT EXISTS idx_events_processed_time ON safety_events(processed_at, occurred_at, event_id);
CREATE INDEX IF NOT EXISTS idx_tokens_account ON mobile_tokens(account_id);
CREATE INDEX IF NOT EXISTS idx_tokens_expiry ON mobile_tokens(expires_at);
CREATE TABLE IF NOT EXISTS login_ip_attempts (
    attempt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip_address TEXT NOT NULL,
    attempted_at BIGINT NOT NULL
);
ALTER TABLE login_ip_attempts ADD COLUMN IF NOT EXISTS attempt_id BIGINT GENERATED BY DEFAULT AS IDENTITY;
DO 'BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = ''login_ip_attempts''::regclass
                   AND contype = ''p'' AND pg_get_constraintdef(oid) = ''PRIMARY KEY (attempt_id)'') THEN
        ALTER TABLE login_ip_attempts DROP CONSTRAINT IF EXISTS login_ip_attempts_pkey;
        ALTER TABLE login_ip_attempts ADD CONSTRAINT login_ip_attempts_pkey PRIMARY KEY (attempt_id);
    END IF;
END';
CREATE INDEX IF NOT EXISTS idx_login_ip_attempts_ip_time ON login_ip_attempts(ip_address, attempted_at);
CREATE TABLE IF NOT EXISTS login_ip_blocks (
    ip_address TEXT PRIMARY KEY,
    blocked_until BIGINT NOT NULL
);
